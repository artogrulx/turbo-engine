#!/usr/bin/env python3
"""Builds the downloadable artefacts of Open Meadow (standard library only).

  * standalone HTML - the whole game (CSS, every script and Three.js) inlined into ONE file
                      that works offline and can be double-clicked or hosted anywhere
  * project ZIP     - the game files, the standalone HTML, a local copy of Three.js so the
                      unzipped folder also works offline, and the multiplayer server

The server (server.py) imports these functions to serve the downloads; run this file to
write the standalone HTML into the repository:

    python3 render/packager.py            # writes open-meadow.html next to index.html
    python3 render/packager.py --stamp    # re-stamps the ?v= versions of index.html's scripts and stylesheet
    python3 render/packager.py --check    # exit 1 if open-meadow.html or the ?v= stamps are out of date
    python3 render/packager.py --zip out.zip

index.html names its scripts and stylesheet as `main.js?v=<hash>`: the hash covers the content of every one of
them, so a new deploy always asks browsers for new files instead of mixing a new page with scripts they cached
(GitHub Pages lets browsers keep files for ten minutes). The packager ignores the `?v=` part when reading files.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import os
import re
import sys
import time
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
THREE_RE = re.compile(r'<!-- three:begin -->.*?<!-- three:end -->', re.S)
SCRIPT_RE = re.compile(r'[ \t]*<script src="([^":?]+)(?:\?[^"]*)?"></script>[ \t]*\n?')
STYLE_RE = re.compile(r'<link rel="stylesheet" href="([^":?]+)(?:\?[^"]*)?">')
# the same two kinds of tag, with the version stamp captured:  <script src="main.js?v=0123456789">
STAMP_RE = re.compile(r'(<script src="|<link rel="stylesheet" href=")([^":?]+)(?:\?v=([0-9a-f]*))?(")')
ZIP_PREFIX = 'open-meadow/'
BANNER = ('<!-- Open Meadow - standalone build: one self-contained file (Three.js r149 is included), '
          'no network needed to play. Generated by render/packager.py; edit the sources, not this file. -->\n')
# index.html carries `window.OPEN_MEADOW_CONFIG = { "server": "" };` - the multiplayer server this copy of the game belongs to.
CONFIG_RE = re.compile(r'window\.OPEN_MEADOW_CONFIG = \{ "server": "([^"]*)" \};')
SERVER_RE = re.compile(r'https?://[A-Za-z0-9](?:[A-Za-z0-9.\-]*[A-Za-z0-9])?(?::[0-9]{1,5})?')


def valid_server(server):
    """http(s)://host[:port] with nothing else: the only characters that can end up inside the page's script."""
    return isinstance(server, str) and SERVER_RE.fullmatch(server) is not None


def with_server(html, server):
    """Sets the default multiplayer server baked into a game page. None leaves the page as it is, '' clears it."""
    if server is None:
        return html
    if server != '' and not valid_server(server):
        raise ValueError('not a valid server address (use http(s)://host[:port]): %r' % (server,))
    new, n = CONFIG_RE.subn(lambda m: 'window.OPEN_MEADOW_CONFIG = { "server": "%s" };' % server, html)
    if n != 1:
        raise ValueError('the page needs exactly one window.OPEN_MEADOW_CONFIG line (found %d)' % n)
    return new


def baked_server(html):
    """The default server baked into a game page ('' if there is none)."""
    m = CONFIG_RE.search(html)
    return m.group(1) if m else ''


def find_root():
    """The folder holding index.html and engine/ (the repository root, or $GAME_DIR)."""
    candidates = []
    if os.environ.get('GAME_DIR'):
        candidates.append(Path(os.environ['GAME_DIR']))
    candidates.append(HERE.parent)
    for c in candidates:
        if (c / 'index.html').is_file() and (c / 'engine').is_dir():
            return c.resolve()
    raise FileNotFoundError('Cannot find the game files (index.html and engine/) next to the render/ folder. '
                            'Deploy from the repository root or set GAME_DIR.')


def vendor_three():
    return (HERE / 'vendor' / 'three.min.js').read_bytes()


def _js(text):
    """Makes JavaScript safe to place inside an inline <script> element."""
    return text.replace('</script', '<\\/script').replace('<!--', '<\\!--')


def _read(root, rel):
    p = (root / rel).resolve()
    p.relative_to(root)   # refuses paths that escape the game folder
    return p.read_text(encoding='utf-8')


def local_scripts(index_html):
    """Local <script src> files in the order index.html loads them (the Three.js block is excluded)."""
    html = THREE_RE.sub('', index_html)
    return [m.group(1) for m in SCRIPT_RE.finditer(html) if '://' not in m.group(1)]   # without any ?v= stamp


def asset_files(index_html):
    """The local stylesheet and script files index.html names, in page order (CDN tags and the bundled Three.js are left out)."""
    html = THREE_RE.sub('', index_html)
    return [m.group(2) for m in STAMP_RE.finditer(html) if not m.group(2).startswith('vendor/')]


def asset_version(root=None, index_html=None):
    """A short hash of the content of every local stylesheet and script: it changes whenever any of them does."""
    root = Path(root) if root else find_root()
    html = index_html if index_html is not None else _read(root, 'index.html')
    h = hashlib.sha1()
    for rel in asset_files(html):
        h.update(rel.encode('utf-8') + b'\0' + _read(root, rel).encode('utf-8') + b'\0')
    return h.hexdigest()[:10]


def stamp_html(index_html, version):
    """index.html with `?v=<version>` on every local script and stylesheet tag."""
    def sub(m):
        if m.group(2).startswith('vendor/'):
            return m.group(0)
        return '%s%s?v=%s%s' % (m.group(1), m.group(2), version, m.group(4))
    return STAMP_RE.sub(sub, index_html)


def stamps_current(root=None):
    """True when every local script / stylesheet tag of index.html carries the version of the files as they are now."""
    root = Path(root) if root else find_root()
    html = _read(root, 'index.html')
    return stamp_html(html, asset_version(root, html)) == html


def build_standalone(root=None, server=None):
    """Returns the single-file standalone game as a string. `server` bakes in the default multiplayer server (see with_server)."""
    root = Path(root) if root else find_root()
    html = _read(root, 'index.html')
    if not THREE_RE.search(html):
        raise ValueError('index.html needs the <!-- three:begin --> ... <!-- three:end --> markers around the Three.js tags')

    def inline_css(m):
        return '<style>\n' + _read(root, m.group(1)).replace('</style', '<\\/style') + '\n</style>'

    def inline_script(m):
        return '<script>\n' + _js(_read(root, m.group(1))) + '\n</script>\n'

    html = STYLE_RE.sub(inline_css, html)
    html = SCRIPT_RE.sub(inline_script, html)
    three = vendor_three().decode('utf-8')
    html = THREE_RE.sub(lambda m: '<script>' + _js(three) + '</script>', html)   # last, so its text is never rescanned
    html = html.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + BANNER, 1)
    left = re.search(r'(?:src|href)="(?:engine/|main\.js|inventory\.js|style\.css)', html)
    if left:
        raise ValueError('standalone build still references %s' % left.group(0))
    return with_server(html, server)


def build_offline_index(root=None):
    """index.html using the bundled vendor/three.min.js instead of a CDN (for the ZIP and the Render-hosted game)."""
    root = Path(root) if root else find_root()
    # the markers are kept, so an unzipped copy can rebuild its own standalone HTML and offline pages
    local = '<!-- three:begin -->\n  <script src="vendor/three.min.js"></script>\n  <!-- three:end -->'
    return THREE_RE.sub(lambda m: local, _read(root, 'index.html'))


def _zip_date(mtime):
    t = time.localtime(mtime)
    return (max(t.tm_year, 1980), t.tm_mon, t.tm_mday, t.tm_hour, t.tm_min, t.tm_sec)


def zip_members(root):
    """(archive path, source Path) for every static file that goes into the ZIP."""
    members = []
    for name in ('style.css', 'main.js', 'inventory.js', 'README.md', 'render.yaml', '.gitignore'):
        if (root / name).is_file():
            members.append((name, root / name))
    for p in sorted((root / 'engine').glob('*.js')):
        members.append(('engine/' + p.name, p))
    members.append(('vendor/three.min.js', HERE / 'vendor' / 'three.min.js'))
    for p in sorted(HERE.rglob('*')):
        rel = p.relative_to(HERE)
        if p.is_file() and not any(part in ('__pycache__', 'data', '.pytest_cache') for part in rel.parts) and p.suffix != '.pyc':
            members.append(('render/' + rel.as_posix(), p))
    return members


def build_zip(root=None, server=None):
    """Returns the project ZIP as bytes. `server` is baked into the zipped index.html and open-meadow.html."""
    root = Path(root) if root else find_root()
    buf = io.BytesIO()
    newest = 0.0
    with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        def add(arc, data, mtime, mode=0o644):
            nonlocal newest
            newest = max(newest, mtime)
            info = zipfile.ZipInfo(ZIP_PREFIX + arc, _zip_date(mtime))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o100000 | mode) << 16
            z.writestr(info, data)

        idx_mtime = (root / 'index.html').stat().st_mtime
        add('index.html', with_server(build_offline_index(root), server).encode('utf-8'), idx_mtime)
        for arc, src in zip_members(root):
            add(arc, src.read_bytes(), src.stat().st_mtime, 0o755 if arc.endswith('server.py') else 0o644)
        add('open-meadow.html', build_standalone(root, server).encode('utf-8'), newest or idx_mtime)
    return buf.getvalue()


def main(argv=None):
    ap = argparse.ArgumentParser(description='Build the Open Meadow standalone HTML (and optionally the ZIP).')
    ap.add_argument('--out', help='standalone HTML path (default: <game folder>/open-meadow.html)')
    ap.add_argument('--zip', help='also write the project ZIP to this path')
    ap.add_argument('--server', default=None, metavar='URL',
                    help='default multiplayer server baked into the page, e.g. https://my-game.onrender.com '
                         '("" removes it; if omitted, the address already baked into the file is kept)')
    ap.add_argument('--stamp', action='store_true', help='only re-stamp the ?v= versions in index.html (no other file is written)')
    ap.add_argument('--check', action='store_true', help='do not write; exit 1 if the standalone HTML on disk or the ?v= stamps in index.html are out of date')
    args = ap.parse_args(argv)
    root = find_root()
    if args.stamp:
        index = root / 'index.html'
        html = index.read_text(encoding='utf-8')
        version = asset_version(root, html)
        new = stamp_html(html, version)
        if new != html:
            index.write_text(new, encoding='utf-8')
        print('index.html asset version %s (%s)' % (version, 'updated' if new != html else 'already current'))
        return 0
    stamps_ok = stamps_current(root)
    out = Path(args.out) if args.out else root / 'open-meadow.html'
    existing = out.read_text(encoding='utf-8') if out.is_file() else ''
    server = args.server if args.server is not None else (baked_server(existing) if existing else None)
    html = build_standalone(root, server).encode('utf-8')
    if not stamps_ok:
        print('warning: the ?v= stamps in index.html are out of date - run: python3 render/packager.py --stamp', file=sys.stderr)
    if args.check:
        fresh = out.is_file() and out.read_bytes() == html
        if fresh:
            print('%s is up to date (%d bytes%s)' % (out, len(html), ', default server %s' % server if server else ''))
        else:
            print('%s is OUT OF DATE - run: python3 render/packager.py' % out)
        return 0 if fresh and stamps_ok else 1
    out.write_bytes(html)
    print('wrote %s (%.0f KB%s)' % (out, len(html) / 1024, ', default server %s' % server if server else ''))
    if args.zip:
        data = build_zip(root, server)
        Path(args.zip).write_bytes(data)
        print('wrote %s (%.0f KB)' % (args.zip, len(data) / 1024))
    return 0


if __name__ == '__main__':
    sys.exit(main())
